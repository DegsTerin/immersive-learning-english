export const nextLanguage = (language) => (language === 'en-GB' ? 'pt-BR' : 'en-GB');

export const createTranslator = (language) => {
  const dictionary = dictionaries[language] || dictionaries['en-GB'];
  const fallback = dictionaries['en-GB'];
  return (key) => {
    const parts = key.split('.');
    const resolve = (source) => parts.reduce((value, part) => value?.[part], source);
    return resolve(dictionary) ?? resolve(fallback) ?? key;
  };
};
